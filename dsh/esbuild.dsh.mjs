#!/usr/bin/env node
/**
 * Build the two committed dsh artifacts:
 *
 *   src/platform/dsh/entry.ts        →  dsh/host.bundle.js   (ESM, Node)
 *   src/platform/dsh/client/main.ts  →  dsh/client.js        (ModuleLoader factory, browser)
 *
 * ## Why the dsh bundle needs a build at all
 *
 * `dsh/index.js` and `dsh/channel.js` are plain JavaScript, and the domain layer is
 * TypeScript. The bundle is installed as a `link:` dependency, so nothing runs at install
 * time — the profile simply points at this directory. Therefore the compiled artifacts have
 * to **exist in the tree and be committed**, the same way the VS Code variants ship a
 * built `dist/`.
 *
 * Hand-porting the asset format instead was rejected: the whole point of the feature is
 * that a package exported here can be imported in VS Code and vice versa, and two
 * implementations of one format diverge. Bundling keeps `src/assets/**` as the single
 * definition. The same argument drives the client build: it bundles xterm, its addons and
 * the reused `webview/terminal` + `webview/server-form` assets, so the dsh panel renders
 * the VS Code variant's actual terminal and form code instead of a second, drifting copy.
 *
 * ## Contracts the outputs must satisfy
 *
 * Host (`host.bundle.js`):
 * - **ESM**, because `dsh/package.json` is `"type": "module"`.
 * - **No bare specifier except the vendoring allowlist** — `dsh/scripts/verify.mjs`
 *   scans the shipped JavaScript, and a `@deepseek-ai/*` specifier is unreachable from a
 *   `link:` install. `ssh2` stays external; `zod` is bundled.
 *
 * Client (`client.js`):
 * - One top-level statement: `window.__ModuleLoader__.load({ id, factory })` — the loader
 *   keys factories by id, and anything executed outside the factory is a page-load side
 *   effect (verify.mjs check 7 asserts exactly this).
 * - `react` external (the browser baseline provides it); everything else inlined, CSS
 *   included (imported as text and injected scoped at runtime — the page belongs to the
 *   Harness, and the reused sheets style `html`/`body` in the original webview).
 *
 * Both:
 * - **Reproducible**, so `--check` means something: the same sources must produce the
 *   same bytes, or "is the committed artifact stale?" has no answer.
 *
 * ## Usage
 *
 *   node dsh/esbuild.dsh.mjs          # rebuild both artifacts
 *   node dsh/esbuild.dsh.mjs --check  # rebuild in memory; fail if either differs from disk
 *
 * `--check` is wired into `npm run verify:dsh`, because a committed build artifact that
 * silently lags its sources is the classic way for a `link:`-installed bundle to run code
 * nobody wrote.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { isBuiltin } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';
import { copyPolicyRuntimeAssets } from '../scripts/copy-policy-assets.mjs';

function prefixNodeBuiltinsPlugin() {
  return {
    name: 'prefix-node-builtins',
    setup(build) {
      build.onResolve({ filter: /.*/ }, (args) => {
        if (args.path.startsWith('node:')) return null;
        if (isBuiltin(args.path)) {
          return { path: `node:${args.path}`, external: true };
        }
        return null;
      });
    }
  };
}

const HERE = dirname(fileURLToPath(import.meta.url));
const BUNDLE_DIR = HERE;
const REPO_DIR = resolve(BUNDLE_DIR, '..');
const checkOnly = process.argv.includes('--check');

/* ---------------------------------- host ---------------------------------- */

const HOST_ENTRY = join(REPO_DIR, 'src', 'platform', 'dsh', 'entry.ts');
const HOST_OUTFILE = join(BUNDLE_DIR, 'host.bundle.js');

const hostBanner = [
  '/*',
  ' * AT Terminal — compiled dsh Host services. DO NOT EDIT.',
  ' *',
  ' * Generated by `node dsh/esbuild.dsh.mjs` from src/platform/dsh/entry.ts.',
  ' * `npm run verify:dsh` fails if this file is not the current build of those sources.',
  ' */'
].join('\n');

const hostOptions = {
  entryPoints: [HOST_ENTRY],
  bundle: true,
  platform: 'node',
  // The Harness ships Node 24; targeting the oldest runtime the plugin claims keeps the
  // output from using syntax the installed runtime would choke on.
  target: 'node22',
  format: 'esm',
  // `ssh2` is a native-assisted dependency the SSH work needs; it stays external so it is
  // resolved at runtime rather than inlined, and so its absence cannot silently turn into
  // a bundled copy with different behaviour.
  external: ['ssh2'],
  // Readable and line-structured: this artifact is committed, so a diff has to be
  // reviewable. It is read from local disk, never served over a network, so size is the
  // least important property here.
  minifyWhitespace: false,
  minifySyntax: true,
  minifyIdentifiers: false,
  legalComments: 'none',
  banner: { js: hostBanner },
  define: {
    MCP_ENABLED: 'true'
  },
  plugins: [prefixNodeBuiltinsPlugin()],
  // Reproducibility: absolute paths must not enter the output.
  absWorkingDir: REPO_DIR,
  logLevel: 'warning'
};

/* --------------------------------- client --------------------------------- */

const CLIENT_ENTRY = join(REPO_DIR, 'src', 'platform', 'dsh', 'client', 'main.ts');
const CLIENT_OUTFILE = join(BUNDLE_DIR, 'client.js');
/** Must equal the bundle's package name: the loader keys factories by it. */
const CLIENT_ID = '@at-series/dsh-at-terminal';

const clientOptions = {
  entryPoints: [CLIENT_ENTRY],
  bundle: true,
  platform: 'browser',
  target: 'es2022',
  // CJS so the output's `require('react')` binds to the factory's `require` parameter —
  // the browser module table provides React, and nothing else may stay external.
  format: 'cjs',
  external: ['react'],
  // The three stylesheets travel as strings and are injected scoped to the panel at
  // runtime (see src/platform/dsh/client/styles.ts) — the Harness page must not be
  // restyled, and a second <link> has no home in a single-file factory.
  loader: { '.css': 'text' },
  minifyWhitespace: false,
  minifySyntax: true,
  minifyIdentifiers: false,
  legalComments: 'none',
  absWorkingDir: REPO_DIR,
  logLevel: 'warning'
};

const clientDocblock = [
  '/*',
  ' * AT Terminal — compiled dsh Client half. DO NOT EDIT.',
  ' *',
  ' * Generated by `node dsh/esbuild.dsh.mjs` from src/platform/dsh/client/**, bundling',
  ' * xterm + addons, the reused webview/terminal building blocks and the stylesheets',
  ' * (injected as text, scoped to the panel). `npm run verify:dsh` fails if this file is',
  ' * not the current build of those sources.',
  ' */'
].join('\n');

/**
 * Wrap the CJS build in the ModuleLoader registration. The wrapper provides the
 * `module`/`exports` the bundle assigns to and returns them, exactly the shape the
 * handwritten first version had; every bundled line is indented so the loader call
 * stays the file's only top-level statement (verify.mjs check 7 walks top-level lines).
 */
function wrapClient(built) {
  const indented = built
    .split('\n')
    .map((line) => (line.length === 0 ? line : `    ${line}`))
    .join('\n');
  return [
    clientDocblock,
    'window.__ModuleLoader__.load({',
    `  id: "${CLIENT_ID}",`,
    '  factory: (require) => {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    indented,
    '    return module.exports;',
    '  }',
    '});',
    ''
  ].join('\n');
}

/* ---------------------------------- drive ---------------------------------- */

async function build(options, transform) {
  const result = await esbuild.build({ ...options, write: false });
  if (result.outputFiles.length !== 1) {
    console.error(`expected one output file, got ${result.outputFiles.length}`);
    process.exit(1);
  }
  return transform(result.outputFiles[0].text);
}

/** Compare one artifact against its rebuild; report and return whether it matched. */
function compare(outfile, built) {
  const name = relative(REPO_DIR, outfile);
  let onDisk;
  try {
    onDisk = readFileSync(outfile, 'utf8');
  } catch {
    console.error(`FAIL  ${name} does not exist; run node dsh/esbuild.dsh.mjs`);
    return false;
  }
  if (onDisk !== built) {
    console.error(`FAIL  ${name} is not the current build of its sources.`);
    console.error('      Run `node dsh/esbuild.dsh.mjs` and commit the result.');
    // A short, targeted diff is more useful than a byte count here.
    const onDiskLines = onDisk.split('\n');
    const builtLines = built.split('\n');
    console.error(`      committed: ${onDiskLines.length} lines / ${onDisk.length} bytes`);
    console.error(`      rebuild:   ${builtLines.length} lines / ${built.length} bytes`);
    for (let index = 0; index < Math.max(onDiskLines.length, builtLines.length); index += 1) {
      if (onDiskLines[index] !== builtLines[index]) {
        console.error(`      first difference at line ${index + 1}`);
        break;
      }
    }
    return false;
  }
  console.log(`OK    ${name} matches its sources (${built.length} bytes)`);
  return true;
}

const identity = (text) => text;
const targets = [
  { outfile: HOST_OUTFILE, build: build(hostOptions, identity) },
  { outfile: CLIENT_OUTFILE, build: build(clientOptions, wrapClient) }
];

if (checkOnly) {
  let ok = true;
  for (const target of targets) {
    if (!compare(target.outfile, await target.build)) ok = false;
  }
  if (!existsSync(join(BUNDLE_DIR, 'policy-assets', 'tree-sitter-bash.wasm'))) {
    console.error('FAIL  dsh/policy-assets are missing; run node dsh/esbuild.dsh.mjs');
    ok = false;
  }
  process.exit(ok ? 0 : 1);
}

for (const target of targets) {
  const built = await target.build;
  writeFileSync(target.outfile, built, 'utf8');
  const lineCount = built.split('\n').length;
  console.log(`built ${relative(REPO_DIR, target.outfile)} — ${lineCount} lines, ${built.length} bytes`);
}

await copyPolicyRuntimeAssets(join(BUNDLE_DIR, 'policy-assets'));
console.log('copied policy assets to dsh/policy-assets');